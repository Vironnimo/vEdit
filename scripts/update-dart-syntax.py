"""Convert the pinned official Dart TextMate grammar to Syntect's YAML format.

No network or third-party Python packages are required. Run from any directory
after deliberately updating assets/syntaxes/dart.upstream.json and its provenance.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets" / "syntaxes"


def captures(source):
    result = {}
    for number, capture in source.items():
        if "name" in capture:
            result[int(number)] = capture["name"]
        elif capture.get("patterns") == [{"include": "#type-args"}]:
            # Sublime capture mappings cannot recursively parse a capture.
            # Preserve its generic-type identity instead of dropping the span.
            result[int(number)] = "meta.generic.dart"
        else:
            raise ValueError(f"Unsupported capture: {capture!r}")
    return result


def pattern(source):
    allowed = {"include", "name", "match", "captures", "begin", "end",
               "beginCaptures", "endCaptures", "contentName", "patterns"}
    if extra := source.keys() - allowed:
        raise ValueError(f"Unsupported rule fields: {extra!r}")
    if "include" in source:
        include = source["include"]
        if not include.startswith("#"):
            raise ValueError(f"Unsupported external include: {include!r}")
        return {"include": include[1:]}
    if "match" in source:
        result = {"match": source["match"]}
        if "name" in source:
            result["scope"] = source["name"]
        if "captures" in source:
            result["captures"] = captures(source["captures"])
        return result
    if "begin" in source:
        result = {"match": source["begin"]}
        if "beginCaptures" in source:
            result["captures"] = captures(source["beginCaptures"])
        inner = []
        if "name" in source:
            inner.append({"meta_scope": source["name"]})
        if "contentName" in source:
            inner.append({"meta_content_scope": source["contentName"]})
        end = {"match": source["end"], "pop": True}
        if "endCaptures" in source:
            end["captures"] = captures(source["endCaptures"])
        # TextMate and Sublime both prioritize the closing match when it starts
        # at the same offset as an inner rule. Dynamic begin/end backreferences
        # remain intact and are handled by Syntect's pushed context.
        inner.append(end)
        inner.extend(pattern(value) for value in source.get("patterns", []))
        result["push"] = inner
        return result
    raise ValueError(f"Unsupported rule: {source!r}")


def scalar(value):
    return json.dumps(value, ensure_ascii=False)


def yaml(value, indent=0):
    """Emit our small YAML subset, keeping capture keys numeric (not strings)."""
    pad = " " * indent
    if isinstance(value, dict):
        for key, child in value.items():
            key = str(key) if isinstance(key, int) else scalar(key)
            if isinstance(child, (dict, list)) and child:
                yield f"{pad}{key}:"
                yield from yaml(child, indent + 2)
            else:
                yield f"{pad}{key}: {scalar(child)}"
    elif isinstance(value, list):
        for child in value:
            if isinstance(child, (dict, list)) and child:
                yield f"{pad}-"
                yield from yaml(child, indent + 2)
            else:
                yield f"{pad}- {scalar(child)}"
    else:
        raise TypeError(type(value))


def main():
    source = json.loads((ASSETS / "dart.upstream.json").read_text(encoding="utf-8"))
    contexts = {"main": [pattern(value) for value in source["patterns"]]}
    for name, rule in source["repository"].items():
        if set(rule) == {"patterns"}:
            contexts[name] = [pattern(value) for value in rule["patterns"]]
        else:
            contexts[name] = [pattern(rule)]
    converted = {
        "name": source["name"],
        "file_extensions": source["fileTypes"],
        "scope": source["scopeName"],
        "contexts": contexts,
    }
    output = "%YAML 1.2\n---\n# Generated by scripts/update-dart-syntax.py. See README.md and DART-LICENSE.txt.\n"
    output += "\n".join(yaml(converted)) + "\n"
    (ASSETS / "Dart.sublime-syntax").write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
